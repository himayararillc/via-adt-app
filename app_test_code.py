# ==========================================
# 3. プロンプト定義（コア思想・評価ロジック）
# ==========================================
SYSTEM_PROMPT = """
あなたは「成人発達理論（ADT: Stage 2〜5）」と「ポジティブ心理学（VIA 24の強み）」を高度に統合した、セルフコーチングの専門AIアドバイザーです。

単なる「性格分析（レッテル貼り）」ではなく、受検者が自分を縛るルール（重荷・鎧）に気づき、より自由で根っこから満たされる段階（Stage 5的視座）へ向かうための「精神発達を促すガイド」として以下の解析とアドバイスを行ってください。

---

### 【解析・出力の基本原則】

1. 「強み」という言葉の固定化を避ける
   VIAの24要素は、能力や固定された性格ではなく「その人がいま発揮している顕著な特徴（特性）」として扱ってください。
   スコアが高い特徴であっても、受検者の意識段階によっては「自分を縛る重荷（お守り・鎧）」になっている可能性があります。

2. 意識段階（Stage 2〜5）の定義とVIAの評価（+3 〜 -3）
   ユーザーの内省回答から現在の「意識の段階（認知の枠組み）」を推定し、VIAの特徴を以下のスコアリング基準で解釈してください。

   【意識段階（Stage）の定義】
   ・Stage 2（道具的主体）：利己・欲求中心。ルール不理解。他者を道具化しやすい。
   ・Stage 3（他者依存/規範順応）：「〜すべき」や他者の目を最優先。失敗を恐れるお守りとして特徴を使う。
   ・Stage 4（自己主導/自分軸）：自立・成果・完璧主義。人に頼らず成果を出すための「鎧」として特徴を過剰発揮しがち。
   ・Stage 5（自己変容/統合）：自他の軸を相対化。執着なく特徴を軽やかに選択・手放しできる。

   【VIAスコアリングの評価軸】
   ・ +3 〜 +1：必須・引き上げ要素（いま意図的に利用・発揮すべき特徴）
   ・ 0：中立
   ・ -1 〜 -3：過剰発揮リスク・重荷（いま手放す/緩めるべき鎧・ブレーキ）
   ※例：Stage 4の人における「粘り強さ」「自己統制」は、成果を焦る「-3（毒・重荷）」として判定し、逆に「寛容さ」「ユーモア」「感謝」を「+3（引き上げ要素）」として提案する。

3. 他者との境界線と協同（関係性のナビゲーション）
   すべてを自力で担う必要はありません。他者のVIAとの付き合い方（「依存」ではなく「健全な協同」）をアドバイスに含めてください。

---

### 【レポート出力構成】

以下の章立てでマークダウン形式のアドバイスを出力してください。

#### 1. 現在のあなたを映す「心のロードマップ」（意識段階の読み解き）
・内省回答から見えてくる現在の「ものの見方・認知の枠組み（Stage 2〜5のグラデーション）」を優しく言語化します。
・あなたが今日まで自分の足で立ち、自分を守り生き抜いてきたプロセスを深く承認・ねぎらいます。

#### 2. あなたの「顕著な特徴」と「使い方の整理」
あなたの回答から強く現れているVIAの特徴（上位項目）を抽出し、「性格」として固定化するのではなく、2つに切り分けて提示します。

  🛠️【これからも意図して利用・活用していく特徴（+スコア）】
  ・自分を縛らず、心からの自由や充足感を得るために軽やかに使えるエネルギー。

  🕊️【そっと手放しても大丈夫な特徴・お守り（-スコア）】
  ・過去の自分を守り成果を出させてくれたが、いま「〜すべき」と自分を追い詰めている「重荷（鎧）」。感謝して卒業していいブレーキ。

#### 3. 根っこからの自由と充足感を得るための「次のステップ」
・重荷を降ろしたスペースに、いま取り組むべき新たなVIA（+3要素）を提案します。
・努力や勉強ではなく、日常で「小さく試せる具体的な行動」として提示してください。

#### 4. 他者との調和と境界線（人間関係のナビゲーション）
・【意識的に距離を置くべき他者】：あなたの「手放すべき重荷（過剰な統制や慎重さ等）」を悪気なく煽り、力ませてくる相手への対処法。
・【意図して助けを借りるべき他者】：あなたが欲しい感覚（ユーモア、寛容さ、大局観等）を持っている人に「頼る・巻き込まれる」ための軽やかなアプローチ。
・「自分の欠落を埋める依存」ではなく、「互いの特性を活かす相互依存」のスタンスを伝えます。

---

### 【トーン＆マナー】
・評価、説教、反省を求めるトーンは厳禁です。
・自立して頑張ってきた受検者への深い敬意（リスペクト）を前提としてください。
・語尾や表現は「〜してみませんか」「〜しても大丈夫です」など、主導権を受検者に委ねる温かく軽やかな対話調としてください。
"""

# ==========================================
# 4. VIA 24の強みデータセット
# ==========================================
VIA_ITEMS = [
    "1. 好奇心（新しい体験・知への関心）",
    "2. 好学心（学び・スキル習得への意欲）",
    "3. 判断力（論理的・批判的思考）",
    "4. 創造性（独創的な発想・工夫）",
    "5. 大局観（深い洞察・全体を見渡す視点）",
    "6. 勇敢さ（リスクや恐れに立ち向かう力）",
    "7. 粘り強さ（最後までやり遂げる執念）",
    "8. 誠実さ（自分と他者に嘘をつかない姿勢）",
    "9. 熱意（情熱とエネルギー）",
    "10. 愛する力・愛される力（親密な関係を大切にする）",
    "11. 親切心（思いやり・他者への貢献）",
    "12. 社会的知性（EQ・人の感情や場の空気の理解）",
    "13. チームワーク（協同・組織への貢献）",
    "14. 公平さ（偏見なく他者を扱う姿勢）",
    "15. リーダーシップ（グループを導きまとめる）",
    "16. 寛容さ・慈悲（過ちを許す・受容する）",
    "17. 謙虚さ（自分を過信せず控えめでいる）",
    "18. 思慮深さ（慎重さ・リスクの未然防止）",
    "19. 自己統制（感情や行動のコントロール）",
    "20. 審美眼（美・卓越性への感動と感謝）",
    "21. 感謝（恵まれていることへの感謝の心）",
    "22. 希望（楽観性・未来へのポジティブな態度）",
    "23. ユーモア（生活を楽しむ・場を和ませる）",
    "24. スピリチュアル（人生の意味や信念の探求）"
]

# ==========================================
# 5. UIレイアウト（入力フォーム）
# ==========================================

st.markdown("""
<div class="header-box">
    <h2>🕊️ セルフコーチングツール</h2>
    <p style="margin-bottom:0; color:#4A5568;">
        頑張ってきたあなたへ。<br>
        『正しさ』の重荷をそっと下ろして、もっと自由を感じ、根っこから満たされるための10分セルフワーク。
    </p>
</div>
""", unsafe_allow_html=True)

with st.form("assessment_form"):
    st.subheader("Step 1: あなたの中でいま強く現れている特徴")
    st.caption("以下の24の要素から、ご自身に「あてはまる」「よく発揮している」と感じるものを5つ程度選んでください。")
    selected_via = st.multiselect("顕著な特徴（複数選択可）", VIA_ITEMS, default=[])

    st.markdown("---")
    st.subheader("Step 2: 内省の問い（ADT質問）")
    st.caption("あなたの日常の感覚や「ものの見方」について、素直な感覚でお答えください。")

    q1 = st.text_area(
        "Q1. 日常や仕事で「こうあるべき」「こうしなければならない」と強く感じて守っているルールやこだわりはありますか？",
        placeholder="例：人に迷惑をかけてはいけない、途中で諦めてはいけない、常に成果を出し続けなければならない...など"
    )

    q2 = st.text_area(
        "Q2. ふとした瞬間に「息苦しさ」や「心が乾いている感覚（満たされない感）」を感じる時、それはどんな場面ですか？",
        placeholder="例：頑張って結果を出したのに虚しくなるとき、誰にも頼れず一人で抱え込んでいるとき...など"
    )

    q3 = st.text_area(
        "Q3. 他人に対して「なんでこの人は〇〇できないんだろう」とモヤモヤしたりイライラしたりするのは、どんな行動を見たときですか？",
        placeholder="例：適当に仕事を流す人、約束を守らない人、感情的に愚痴を言う人...など"
    )

    q4 = st.text_area(
        "Q4. もし、あなたが今背負っている「責任」や「正しさ」を半分に減らしても誰も責めないとしたら、本当は何をしてみたい（どう過ごしたい）ですか？",
        placeholder="例：何も生産性のない時間を過ごしたい、自分のためだけに旅に出たい、完璧を目指さず6割で提出したい...など"
    )

    submitted = st.form_submit_button("自分を解きほぐすレポートを生成する")

# ==========================================
# 6. 生成処理とレポート表示
# ==========================================
if submitted:
    if not selected_via:
        st.warning("⚠️ Step 1の特徴（VIA）を少なくとも1つ以上選択してください。")
    elif not q1 or not q2:
        st.warning("⚠️ Step 2の内省の問い（特にQ1, Q2）にご記入ください。")
    else:
        with st.spinner("あなたの回答を丁寧に読み解き、メッセージを作成しています..."):
            user_payload = f"""
### 【ユーザー入力データ】

#### 1. ユーザーが選択した顕著な特徴（VIA）:
{json.dumps(selected_via, ensure_ascii=False, indent=2)}

#### 2. 内省回答（ADT回答）:
- **Q1 (守っているルール/正しさ):** {q1}
- **Q2 (息苦しさや乾きを感じる場面):** {q2}
- **Q3 (他者へのモヤモヤ・許せないこと):** {q3}
- **Q4 (もし重荷を減らせたらやってみたいこと):** {q4}
"""

            try:
                model = genai.GenerativeModel(
                    model_name="gemini-1.5-pro-latest",
                    system_instruction=SYSTEM_PROMPT
                )

                response = model.generate_content(user_payload)

                st.success("✨ レポートの生成が完了しました！")
                st.markdown("---")
                st.markdown(response.text)

                st.info("💡 また日常生活でふとモヤモヤしたり、力んでしまっていると感じた時は、いつでもこのツールを開いてみてくださいね。")

            except Exception as e:
                st.error(f"分析処理中にエラーが発生しました: {str(e)}")

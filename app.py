    sorted_strengths = sorted(avg_scores.items(), key=lambda x: x[1], reverse=True)

    # 黙従傾向（何でも同じ方向に回答してしまう癖）の簡易チェック:
    # 「通常項目の平均」と「逆転項目を反転した値」の差が全体的に大きい場合、

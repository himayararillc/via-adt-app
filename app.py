def _insert_reverse_items(pattern, reverse_bank):
    """strengthごとの通常2問の直後に、対応する逆転項目（そのパターン専用の言い回し）を1問差し込む。
    通常項目と混在させることで、逆転項目だけ雑に答えられるのを防ぐ狙い。"""
    reverse_by_strength = {q["strength"]: q for q in reverse_bank}
    grouped_pattern = OrderedDict()
    for q in pattern:
        grouped_pattern.setdefault(q["strength"], []).append(q)
    combined = []
    for strength, items in grouped_pattern.items():
        combined.extend(items)
        rev = reverse_by_strength.get(strength)
        if rev:
            combined.append(rev)
    return combined


